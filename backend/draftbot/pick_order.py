def _key(name: str) -> str:
    return (name or "").split(" // ")[0].strip().lower()


def lsv_rounds(drafts: Iterable[dict], exclude: Optional[str] = None) -> Dict[str, list]:
    """Per card, the round it went in each of LSV's reconstructed drafts (None: not taken in the rounds
    reconstructed), with each draft's recorded rounds: {name: [(round or None, rounds_recorded), ...]}."""
    drafts = [d for d in drafts if d["video"] != exclude]
    taken = []
    for d in drafts:
        n = d["seats"]
        seen = {}
        for i, (_, card) in enumerate(d["picks"]):
            if card != "?":
                seen.setdefault(_key(card), i / n + 1)       # fractional, as in the VRD tables
        taken.append((seen, len(d["picks"]) // n))
    names = {c for seen, _ in taken for c in seen}
    return {c: [(seen.get(c), rounds) for seen, rounds in taken] for c in names}


def combined_order(drafts: Iterable[dict], lsv_weight: float, vrd_weight: float, group_weight: float,
                   exclude: Optional[str] = None) -> Dict[str, Tuple[float, int]]:
    """One average round per card from all three sources, LSV's tables first (owner, 2026-10-21).

    Each source's estimate counts once per draft that took the card, times the source's weight. LSV's drafts are
    only reconstructed for their first rounds, so a draft where he didn't take a card within the recorded rounds
    counts as "later than that", using the other sources' estimate when that is later still. Keys are lower-case
    names; values (average round, drafts that took it across all sources)."""
    other: Dict[str, Tuple[float, float, int]] = {}
    for table, w in ((PICK_ORDER, vrd_weight), (GROUP_ORDER, group_weight)):
        for name, (avg, cnt) in table.items():
            k = _key(name)
            s, ws, n = other.get(k, (0.0, 0.0, 0))
            other[k] = (s + w * max(cnt, 1) * avg, ws + w * max(cnt, 1), n + cnt)
    out = {k: (s / ws, n) for k, (s, ws, n) in other.items() if ws > 0}
    for k, rows in lsv_rounds(drafts, exclude).items():
        prior = out.get(k, (None, 0))[0]
        vals = [r if r is not None else max(rec + 1, prior or rec + 6) for r, rec in rows]
        took = sum(r is not None for r, _ in rows)
        est = sum(vals) / len(vals)
        s, ws, n = other.get(k, (0.0, 0.0, 0))
        ws_l = lsv_weight * took
        out[k] = ((s + ws_l * est) / (ws + ws_l), n + took)
    return {k: (round(a, 1), n) for k, (a, n) in out.items()}
